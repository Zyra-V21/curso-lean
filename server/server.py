#!/usr/bin/env python3
"""Local server for the Lean reading course.

Serves the static course and keeps an append-only event log
(tutor/events.jsonl) that the tutor (Claude) reads in later sessions.
Binds to 127.0.0.1 only. Standard library only.
"""

import argparse
import json
import os
import threading
import time
from http import HTTPStatus
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COURSE_DIR = ROOT / "course"
EVENTS_FILE = ROOT / "tutor" / "events.jsonl"
MAX_BODY = 64 * 1024
MAX_EVENT = 16 * 1024
WRITE_LOCK = threading.Lock()


def read_events():
    if not EVENTS_FILE.exists():
        return []
    events = []
    with EVENTS_FILE.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                # A torn line must never break the whole log.
                continue
    return events


def append_events(events):
    EVENTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    now = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    for event in events:
        event = dict(event)
        event["serverAt"] = now
        lines.append(json.dumps(event, ensure_ascii=False, separators=(",", ":")))
    payload = ("\n".join(lines) + "\n").encode("utf-8")
    with WRITE_LOCK:
        fd = os.open(EVENTS_FILE, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o644)
        try:
            os.write(fd, payload)
            os.fsync(fd)
        finally:
            os.close(fd)


def validate(event):
    if not isinstance(event, dict):
        return False
    if not isinstance(event.get("type"), str) or not event["type"]:
        return False
    return len(json.dumps(event, ensure_ascii=False)) <= MAX_EVENT


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(COURSE_DIR), **kwargs)

    def end_headers(self):
        # Lessons get regenerated by the tutor; never serve stale copies.
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, fmt, *args):
        if self.path.startswith("/api/"):
            super().log_message(fmt, *args)

    def send_json(self, status, body):
        data = json.dumps(body, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path == "/api/health":
            return self.send_json(HTTPStatus.OK, {"ok": True})
        if self.path == "/api/info":
            return self.send_json(HTTPStatus.OK, {"root": str(ROOT)})
        if self.path == "/api/events":
            return self.send_json(HTTPStatus.OK, read_events())
        if self.path.startswith("/api/"):
            return self.send_json(HTTPStatus.NOT_FOUND, {"error": "unknown endpoint"})
        return super().do_GET()

    def do_POST(self):
        if self.path != "/api/events":
            return self.send_json(HTTPStatus.NOT_FOUND, {"error": "unknown endpoint"})
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            length = 0
        if length <= 0 or length > MAX_BODY:
            return self.send_json(HTTPStatus.BAD_REQUEST, {"error": "bad body size"})
        try:
            body = json.loads(self.rfile.read(length).decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            return self.send_json(HTTPStatus.BAD_REQUEST, {"error": "invalid json"})
        events = body if isinstance(body, list) else [body]
        if not events or not all(validate(e) for e in events):
            return self.send_json(HTTPStatus.BAD_REQUEST, {"error": "invalid event"})
        append_events(events)
        return self.send_json(HTTPStatus.OK, {"ok": True, "stored": len(events)})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8642)
    parser.add_argument("--events", type=Path, default=None, help="event log path (for testing)")
    args = parser.parse_args()
    if args.events:
        global EVENTS_FILE
        EVENTS_FILE = args.events.resolve()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"Lean course at http://127.0.0.1:{args.port}/", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
